export function generateCreatureName(nextRand: () => number): string {
  const first = FIRST_NAMES[Math.floor(nextRand() * FIRST_NAMES.length)];
  const last = SURNAMES[Math.floor(nextRand() * SURNAMES.length)];
  return `${first} ${last}`;
}
